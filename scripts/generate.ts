// Reads openapi.json and writes src/schema.d.ts, src/modules/*.ts and src/client.ts.
// Run it with `bun run generate`. Never edit the files it writes.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript";
import ts from "typescript";

const HTTP_METHODS = ["get", "post", "put", "patch", "delete"] as const;
type HttpMethod = (typeof HTTP_METHODS)[number];

function isHttpMethod(method: string): method is HttpMethod {
  return HTTP_METHODS.some((known) => known === method);
}

interface Parameter {
  $ref?: string;
  name?: string;
  in?: string;
  required?: boolean;
}

interface RequestBody {
  $ref?: string;
  required?: boolean;
  content?: Record<string, { schema?: unknown }>;
}

interface ResponseEntry {
  $ref?: string;
  content?: Record<string, unknown>;
}

interface Operation {
  operationId: string;
  summary?: string;
  description?: string;
  deprecated?: boolean;
  parameters?: Parameter[];
  requestBody?: RequestBody;
  responses: Record<string, ResponseEntry>;
}

interface Doc {
  paths: Record<string, Partial<Record<HttpMethod, Operation>>>;
  components: {
    parameters?: Record<string, Parameter>;
    requestBodies?: Record<string, RequestBody>;
    responses?: Record<string, ResponseEntry>;
  };
}

const SPEC_FILE = "openapi.json";
const CLIENT_CLASS = "GitHubClient";
const HEADER =
  "// Generated by scripts/generate.ts from openapi.json. Do not edit.\n";

const EM_DASH = String.fromCharCode(0x2014);

function cleanProse(text: string): string {
  return text
    .replaceAll(` ${EM_DASH} `, ", ")
    .replaceAll(EM_DASH, ", ")
    .replaceAll(" - ", ": ");
}

function pruneDoc(key: string, value: unknown): unknown {
  if (
    key === "x-webhooks" ||
    key === "webhooks" ||
    key === "example" ||
    key === "examples" ||
    key === "x-github" ||
    key === "x-octokit" ||
    key === "x-github-Overlays" ||
    key === "x-github-internal" ||
    key === "x-github-breaking-changes" ||
    key === "externalDocs"
  ) {
    return undefined;
  }
  if (
    (key === "description" || key === "summary") &&
    typeof value === "string"
  ) {
    return cleanProse(value);
  }
  return value;
}

// Method JSDocs in src/modules/*.ts carry the operation summaries and descriptions, so schema.d.ts
// keeps only the types that paths reach.
function pruneSpec(key: string, value: unknown): unknown {
  if (key === "description" || key === "summary" || key === "headers") {
    return undefined;
  }
  return pruneDoc(key, value);
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

const text = readFileSync(SPEC_FILE, "utf8");
const spec: OpenAPI3 = JSON.parse(text, pruneSpec);
const doc: Doc = JSON.parse(text, pruneDoc);

// GitHub's spec puts response examples inside a schema-less requestBody on GET /repos/{owner}/{repo}/contents/{path},
// and attaches an invalid discriminator to its oneOf response where content-directory is an array.
const getContentOp = doc.paths["/repos/{owner}/{repo}/contents/{path}"]?.get;
if (getContentOp) {
  delete getContentOp.requestBody;
}

if (isRecord(spec.paths)) {
  const getContentItem = spec.paths["/repos/{owner}/{repo}/contents/{path}"];
  if (isRecord(getContentItem) && isRecord(getContentItem.get)) {
    delete getContentItem.get.requestBody;
    const responses = getContentItem.get.responses;
    if (isRecord(responses) && isRecord(responses["200"])) {
      const content = responses["200"].content;
      if (isRecord(content) && isRecord(content["application/json"])) {
        const schema = content["application/json"].schema;
        if (isRecord(schema)) {
          delete schema.discriminator;
        }
      }
    }
  }

  for (const item of Object.values(spec.paths)) {
    if (!isRecord(item)) continue;
    for (const op of Object.values(item)) {
      if (!isRecord(op) || !isRecord(op.responses)) continue;
      for (const status of Object.keys(op.responses)) {
        if (!status.startsWith("2")) {
          delete op.responses[status];
        }
      }
    }
  }
}

const reachableRefs = new Set<string>();
const specComponents = isRecord(spec.components) ? spec.components : undefined;

function collectRefs(node: unknown): void {
  if (Array.isArray(node)) {
    for (const item of node) collectRefs(item);
    return;
  }
  if (!isRecord(node)) return;
  if (typeof node.$ref === "string" && !reachableRefs.has(node.$ref)) {
    reachableRefs.add(node.$ref);
    const [, , section, name] = node.$ref.split("/");
    const bucket =
      section && specComponents ? specComponents[section] : undefined;
    const target = name && isRecord(bucket) ? bucket[name] : undefined;
    if (target) collectRefs(target);
  }
  for (const child of Object.values(node)) {
    collectRefs(child);
  }
}
collectRefs(spec.paths);

for (const [section, entries] of Object.entries(specComponents ?? {})) {
  if (!isRecord(entries)) continue;
  for (const name of Object.keys(entries)) {
    if (!reachableRefs.has(`#/components/${section}/${name}`)) {
      delete entries[name];
    }
  }
}

function words(name: string): string[] {
  return name.split(/[^a-zA-Z0-9]+/).filter(Boolean);
}

function pascalCase(name: string): string {
  return words(name)
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join("");
}

function camelCase(name: string): string {
  const pascal = pascalCase(name);
  return pascal[0].toLowerCase() + pascal.slice(1);
}

function nameOf(op: Operation): { group: string; method: string } {
  const parts = op.operationId.split("/");
  if (parts.length !== 2 || !parts[0] || !parts[1]) {
    throw new Error(`Unexpected operationId "${op.operationId}".`);
  }
  return { group: camelCase(parts[0]), method: camelCase(parts[1]) };
}

function docComment(op: Operation): string {
  const lines = [op.summary ?? ""];
  if (op.description && op.description !== op.summary) {
    lines.push(op.description);
  }
  if (op.deprecated) {
    lines.push("@deprecated GitHub lists this endpoint as deprecated.");
  }
  const body = cleanProse(lines.filter(Boolean).join("\n\n")).replaceAll(
    "*/",
    "*\\/",
  );
  return `/**\n${body
    .split("\n")
    .map((line) => ` * ${line}`.trimEnd())
    .join("\n")}\n */`;
}

function pathEntry(param: string): string {
  const arg = camelCase(param);
  return arg === param ? param : `${JSON.stringify(param)}: ${arg}`;
}

function resolveParam(param: Parameter): Parameter {
  if (!param.$ref) return param;
  const name = param.$ref.split("/").pop() ?? "";
  const found = doc.components.parameters?.[name];
  if (!found) throw new Error(`No parameter ${param.$ref} in ${SPEC_FILE}.`);
  return found;
}

function resolveRequestBody(
  body: RequestBody | undefined,
): RequestBody | undefined {
  if (!body) return undefined;
  if (!body.$ref) return body;
  const name = body.$ref.split("/").pop() ?? "";
  const found = doc.components.requestBodies?.[name];
  if (!found) throw new Error(`No requestBody ${body.$ref} in ${SPEC_FILE}.`);
  return found;
}

function resolveResponse(response: ResponseEntry): ResponseEntry {
  if (!response.$ref) return response;
  const name = response.$ref.split("/").pop() ?? "";
  const found = doc.components.responses?.[name];
  if (!found) throw new Error(`No response ${response.$ref} in ${SPEC_FILE}.`);
  return found;
}

function bodyKind(
  endpoint: Endpoint,
): { kind: "json" | "text" | "binary"; required: boolean } | undefined {
  const { path, method, op } = endpoint;
  const resolved = resolveRequestBody(op.requestBody);
  const content = resolved?.content ?? {};
  const entries = Object.entries(content).filter(([, media]) => media?.schema);
  if (!entries.length) return undefined;
  const types = entries.map(([mediaType]) => mediaType);
  if (types.includes("application/json")) {
    return { kind: "json", required: Boolean(resolved?.required) };
  }
  if (types.includes("text/plain") || types.includes("text/x-markdown")) {
    return { kind: "text", required: Boolean(resolved?.required) };
  }
  if (types.includes("application/octet-stream")) {
    return { kind: "binary", required: true };
  }
  throw new Error(
    `${method} ${path} sends ${types.join(", ")}, which this script does not render.`,
  );
}

// Returns true when the endpoint returns a raw stream/text Response instead of JSON or 204/205 empty.
function returnsRawResponse(op: Operation): boolean {
  const entries = Object.entries(op.responses).map(
    ([status, r]) => [status, resolveResponse(r)] as const,
  );
  const twoXx = entries.filter(([status]) => status.startsWith("2"));
  if (!twoXx.length) {
    return entries.some(([status]) => status === "302");
  }
  const hasJson = twoXx.some(([, res]) =>
    Boolean(res.content?.["application/json"]),
  );
  if (hasJson) return false;
  const hasOtherContent = twoXx.some(
    ([, res]) => Object.keys(res.content ?? {}).length > 0,
  );
  return hasOtherContent;
}

interface Endpoint {
  name: string;
  path: string;
  method: HttpMethod;
  op: Operation;
}

const groups = new Map<string, Endpoint[]>();
for (const [path, item] of Object.entries(doc.paths)) {
  for (const [method, op] of Object.entries(item)) {
    if (!isHttpMethod(method) || !op) continue;
    const { group, method: name } = nameOf(op);
    const endpoints = groups.get(group) ?? [];
    if (endpoints.some((endpoint) => endpoint.name === name)) {
      throw new Error(
        `Two operations in "${group}" are named "${name}". Change nameOf to tell them apart.`,
      );
    }
    endpoints.push({ name, path, method, op });
    groups.set(group, endpoints);
  }
}

function renderMethod(endpoint: Endpoint): string {
  const { name, path, method, op } = endpoint;
  const params = (op.parameters ?? []).map(resolveParam);
  const inPath = [...path.matchAll(/\{([^}]+)\}/g)].map((match) => match[1]);
  const query = params.filter((param) => param.in === "query");
  const queryRequired = query.some((param) => param.required);
  const body = bodyKind(endpoint);

  const type = `"${path}", "${method}"`;
  const args = inPath.map(
    (param) => `${camelCase(param)}: PathParams<${type}>["${param}"]`,
  );
  const send: string[] = [];
  if (inPath.length) {
    send.push(`path: { ${inPath.map(pathEntry).join(", ")} }`);
  }

  const pushQuery = () => {
    if (!query.length) return;
    args.push(`query${queryRequired ? "" : "?"}: Query<${type}>`);
    send.push("query");
  };

  const pushBody = () => {
    if (!body) return;
    const optional = !body.required && !queryRequired ? "?" : "";
    args.push(`body${optional}: Body<${type}>`);
    send.push(`${body.kind}: body`);
  };

  if (body && body.required && !queryRequired) {
    pushBody();
    pushQuery();
  } else {
    pushQuery();
    pushBody();
  }

  args.push("options?: CallOptions");

  const call = returnsRawResponse(op) ? "download" : "send";
  return `${docComment(op)}\n${name}(${args.join(", ")}) {\n  return this.http.${call}("${method}", "${path}", { ${send.join(", ")} }, options);\n}`;
}

function renderModule(group: string, endpoints: Endpoint[]): string {
  const source = endpoints.map(renderMethod).join("\n\n");
  const names = ["Body", "CallOptions", "PathParams", "Query"].filter((name) =>
    new RegExp(`\\b${name}\\b`).test(source),
  );
  return `${HEADER}import { ${[...names, "Transport"].map((name) => `type ${name}`).join(", ")} } from "../http";

export class ${pascalCase(group)}Module {
  constructor(private readonly http: Transport) {}

${source}
}
`;
}

function renderClient(groupNames: string[]): string {
  const modules = groupNames.map((name) => ({
    name,
    className: `${pascalCase(name)}Module`,
  }));
  return `${HEADER}import { Transport, type GitHubConfig } from "./http";
${modules.map(({ name, className }) => `import { ${className} } from "./modules/${name}";`).join("\n")}

export class ${CLIENT_CLASS} {
${modules.map(({ name, className }) => `  readonly ${name}: ${className};`).join("\n")}

  constructor(config: GitHubConfig | string = {}) {
    const http = new Transport(typeof config === "string" ? { token: config } : config);
${modules.map(({ name, className }) => `    this.${name} = new ${className}(http);`).join("\n")}
  }
}
`;
}

const types = await openapiTS(spec, {
  transform: (schema) =>
    schema.format === "binary"
      ? ts.factory.createTypeReferenceNode("Blob")
      : undefined,
});

rmSync("src/modules", { recursive: true, force: true });
mkdirSync("src/modules", { recursive: true });
writeFileSync("src/schema.d.ts", cleanProse(astToString(types)));
for (const [group, endpoints] of groups) {
  writeFileSync(`src/modules/${group}.ts`, renderModule(group, endpoints));
}
writeFileSync("src/client.ts", renderClient([...groups.keys()]));
console.log(
  [...groups]
    .map(([group, endpoints]) => `${group}: ${endpoints.length}`)
    .join(", "),
);
